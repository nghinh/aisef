#: `## Epic 1: Note-taking foundation`
_EPIC_HEADING = re.compile(r"^#{2,5}\s+Epic\s+(\d+)\s*[:：—–-]\s*(.+?)\s*$", re.MULTILINE | re.IGNORECASE)
#: `### Story 1.2: Edit note` — fixed pattern in BMAD template.
#: `### Story 1.1: Title` — and the shapes a planner reaches for when the
#: framework has been calling the same thing `STORY-01-01` all along:
#: `Story 01-01:`, `Story STORY-01-01:`, `STORY-01-01:` (bug 105, 2026-09-13:
#: the size gate asked for a split, the agent rewrote the headings with a
#: hyphen, and every story in the file vanished — "no readable stories found
#: in epics.md", with the plan pipeline stopped).
_STORY_HEADING = re.compile(
    r"^#{2,5}\s+(?:Story\s+(?:STORY[-_])?|STORY[-_])(\d+)[.\-_](\d+)"
    r"\s*[:：—–-]\s*(.+?)\s*$",
    re.MULTILINE | re.IGNORECASE,
)
#: Acceptance criteria block ends at a new heading or another **bold label**
#: — but *not* at `**When**`/`**Then**`/`**And**`, which are body parts of
#: the criteria themselves. Cutting there leaves each story with one truncated criterion.
_AC_HEAD = (
    r"(?:Acceptance Criteria|Tiêu chí chấp nhận|Tiêu chí kiểm chứng"
    r"|Tiêu chí nghiệm thu"
    r"|(?:Testable|Verifiable|Acceptance|Verification|Test)\s+(?:criteria|consequences|conditions)"
    r"|Criteria|Tiêu chí|Hệ quả(?:\s+kiểm chứng(?:\s+được)?)?)"
)
_AC_BLOCK = re.compile(
    r"(?:\*\*" + _AC_HEAD + r"\s*[:：]?\*\*"
    r"|#{2,5}\s+" + _AC_HEAD + r")"
    r"\s*[:：]?\s*\n(.*?)"
    r"(?=\n#{2,5}\s|\n\s*\*\*(?!Given|When|Then|And)[^\n*]+\*\*\s*[:：]?\s*\n|\Z)",
    re.DOTALL | re.IGNORECASE,
)
#: A criterion opens with Given. Two real variants beyond `**Given**` (bug 91,
#: 2026-09-13): the planner chains scenarios as `**And** **Given** …`, which
#: made eight criteria parse as one and slipped straight through the
#: `story.max_acceptance_criteria` gate; and plain unbolded `Given`, which
#: went the other way — every line counted as its own criterion, inflating
#: the count and failing the gate on a story that was the right size.
_GIVEN = re.compile(
    r"^\s*(?:\*{0,2}(?:And|Và)\*{0,2}\s+)?\*{0,2}Given\*{0,2}\s",
    re.IGNORECASE,
)
_AND_PREFIX = re.compile(
    r"^\s*\*{0,2}(?:And|Và)\*{0,2}\s+(?=\*{0,2}Given)", re.IGNORECASE
)
#: `- write_scope: src/notes/, src/db/schema.ts` — including when labels are bold.
_META_ITEM = re.compile(
    r"^[-*]?\s*\*{0,2}(covers|write[_ ]scope|depends[_ ]on|screens?|verification[_ ]contract)\*{0,2}\s*[:：]\s*(.+?)\s*$",
    re.MULTILINE | re.IGNORECASE,
)
_STORY_REF = re.compile(r"\b(\d+)\.(\d+)\b")
#: Coverage map lines that explicitly say there is **no** story. Skip them:
#: a real BMAD line is "FR-13 -> NO STORY. ... Binds AR-18 at Story 1.2",
#: and if we only look for "has FR code + has story number" then FR-13 gets
#: assigned to story 1.2 — then the machine gate blocks the entire story set
#: because of one prose sentence.
_NO_STORY = re.compile(
    r"(không có story|chưa có story|no story|ngoài phạm vi|out of scope|n/a)", re.I
)
#: The third line is optional because planners also write the two-line form,
#: with the purpose folded into the I-want line (bug 92, 2026-09-13:
#: `I want to type a note so that it is saved` — the whole role block was
#: dropped from every story file, and the agent never saw who it was for).
_ROLE_LINE = re.compile(
    r"^\s*(?:As an?|Tôi là)\s+(.+?),?\s*$\n"
    r"^\s*(?:I want|Tôi muốn)\s+(.+?),?\s*$"
    r"(?:\n^\s*(?:So that|Để)\s+(.+?)\.?\s*$)?",
    re.MULTILINE | re.IGNORECASE,
)
#: `so that` is the template, but real planner output writes `so I can`,
#: `so it`, or a bare `so` (6 of 7 stories in the todo-oc run).
_SO_THAT_INLINE = re.compile(r",?\s+(?:so that|so|để)\s+", re.IGNORECASE)


def _role_parts(m: re.Match[str]) -> tuple[str, str, str]:
    """`As a … / I want … / So that …` — the third part may be inline."""
    as_a, i_want, so_that = (" ".join((g or "").split()) for g in m.groups())
    if not so_that:
        parts = _SO_THAT_INLINE.split(i_want, maxsplit=1)
        if len(parts) == 2:
            i_want, so_that = parts[0].rstrip(","), parts[1]
    return (as_a.strip("*").strip(), i_want.strip("*").strip(),
            so_that.rstrip(".").strip())


def epic_id(n: int | str) -> str:
    return f"EPIC-{int(n):02d}"


def story_id(epic: int | str, seq: int | str) -> str:
    return f"STORY-{int(epic):02d}-{int(seq):02d}"


@dataclass
class Story:
    """A normalized story — the unit of work for one agent session."""

    id: str
    epic_id: str
    title: str
    as_a: str = ""
    i_want: str = ""
    so_that: str = ""
    acceptance_criteria: list[str] = field(default_factory=list)
    #: FR codes this story covers. Machine gate cross-references with the PRD.
    covers: list[str] = field(default_factory=list)
    #: Paths the story is allowed to write. Guard blocks according to this list,
    #: and merge conflicts at wave end are evidence of a misdeclared scope.
    write_scope: list[str] = field(default_factory=list)
    depends_on: list[str] = field(default_factory=list)
    #: Screens this story builds (codes from EXPERIENCE.md). Empty = story has
    #: no UI; the mockup map step skips it.
    screens: list[str] = field(default_factory=list)
    #: Verification kinds this story must pass. If the story declares them,
    #: the declaration is used; otherwise inferred by code. Not a new phase —
    #: just making explicit what "done" means for **this story**, instead of
    #: a single default for all stories.
    verification_contract: list[str] = field(default_factory=list)
    body: str = ""

    @property
    def epic_seq(self) -> tuple[int, int]:
        parts = self.id.split("-")
        return int(parts[1]), int(parts[2])

    def as_dict(self) -> dict:
        return {
            "id": self.id,
            "epic_id": self.epic_id,
            "title": self.title,
            "as_a": self.as_a,
            "i_want": self.i_want,
            "so_that": self.so_that,
            "acceptance_criteria": self.acceptance_criteria,
            "covers": self.covers,
            "write_scope": self.write_scope,
            "verification_contract": self.verification_contract,
            "depends_on": self.depends_on,
            "screens": self.screens,
        }


@dataclass
class Epic:
    id: str
    title: str
    goal: str = ""
    stories: list[Story] = field(default_factory=list)


@dataclass
class EpicPlan:
    epics: list[Epic] = field(default_factory=list)
    #: FR -> story, read from the "FR Coverage Map" section if BMAD generated one.
    coverage_map: dict[str, list[str]] = field(default_factory=dict)

    def stories(self) -> list[Story]:
        return [s for e in self.epics for s in e.stories]

    def by_id(self, sid: str) -> Story | None:
        return next((s for s in self.stories() if s.id == sid), None)


def _split_ac(block: str) -> list[str]:
    """Split an acceptance criteria block into individual criteria.

    Two patterns observed in practice: multi-line Given/When/Then, and
    bullet lists. Given opens a new criterion; otherwise each bullet is
    one criterion.
    """
    items: list[str] = []
    current: list[str] = []

    for raw in block.splitlines():
        line = raw.strip()
        if not line or _META_ITEM.match(line):
            continue  # metadata line, not a criterion
        if _GIVEN.match(line):
            if current:
                items.append(" ".join(current))
            # Drop the chaining `And` — it introduced the previous scenario,
            # and a criterion that opens with "And Given" reads as the tail of
            # something the agent cannot see.
            current = [_AND_PREFIX.sub("", line, count=1)]
        elif current:
            current.append(line)
        else:
            m = _BULLET.match(line)
            items.append(m.group(1) if m else line)
    if current:
        items.append(" ".join(current))

    cleaned = [" ".join(i.replace("**", "").split()) for i in items]
    return [c for c in cleaned if c]


def _split_list(text: str) -> list[str]:
    """`a, b · c` -> ['a', 'b', 'c']. Strips quotes and bold markers."""
    parts = re.split(r"[,;·]| và ", text)
    return [p.strip().strip("`\"'*") for p in parts if p.strip().strip("`\"'*")]


def _parse_story_meta(body: str, epic_n: int) -> dict[str, list[str]]:
    meta: dict[str, list[str]] = {}
    for m in _META_ITEM.finditer(body):
        key = m.group(1).lower().replace(" ", "_")
        values = _split_list(m.group(2))
        if key == "covers":
            meta["covers"] = _expand_fr_refs(m.group(2))
        elif key == "verification_contract":
            meta["verification_contract"] = [v.strip().lower() for v in values if v.strip()]
        elif key == "write_scope":
            meta["write_scope"] = [v for v in values if v.lower() not in ("none", "không")]
        elif key == "depends_on":
            meta["depends_on"] = _refs_to_story_ids(m.group(2), epic_n)
        elif key in ("screen", "screens"):
            meta["screens"] = [
                slugify(v) for v in values if v.lower() not in ("none", "không")
            ]
    return meta


def _refs_to_story_ids(text: str, default_epic: int) -> list[str]:
    """`1.1, 2.3` or `STORY-01-01` -> normalized story id."""
    out = []
    for m in re.finditer(r"STORY-(\d+)-(\d+)", text, re.IGNORECASE):
        out.append(story_id(m.group(1), m.group(2)))
    for m in _STORY_REF.finditer(text):
        sid = story_id(m.group(1), m.group(2))
        if sid not in out:
            out.append(sid)
    return out


def _parse_coverage_map(text: str) -> dict[str, list[str]]:
    """Parse the "FR Coverage Map" section — table or bullet list, both accepted.

    Any line with at least one FR code and one story number counts as a
    mapping line; no rigid table format, because the model formats
    differently each time.
    """
    m = re.search(r"^#{2,4}\s+(?:FR[- ]?(?:Story\s+)?Coverage\s+Map|(?:Requirements?\s+)?Coverage(?:\s+Map)?|Bản đồ phủ FR)\s*$", text, re.MULTILINE | re.IGNORECASE)
    if not m:
        return {}
    section = text[m.end():]
    end = re.search(r"^#{2,3}\s+\S", section, re.MULTILINE)
    if end:
        section = section[: end.start()]

    mapping: dict[str, list[str]] = {}
    for line in section.splitlines():
        frs = _expand_fr_refs(line)
        if not frs or _NO_STORY.search(line):
            continue
        refs = [story_id(a, b) for a, b in _STORY_REF.findall(line)]
        for fr in frs:
            mapping.setdefault(fr, [])
            for r in refs:
                if r not in mapping[fr]:
                    mapping[fr].append(r)
    return mapping


def parse_epics(text: str) -> EpicPlan:
    """BMAD's `epics.md` -> normalized epics and stories."""
    plan = EpicPlan(coverage_map=_parse_coverage_map(text))

    epic_marks = list(_EPIC_HEADING.finditer(text))
    # One epic can carry more than one heading: BMAD writes an `## Epic List`
    # summary and then a detail section per epic, both titled `Epic N: …`
    # (bug 89, 2026-09-13 — the summary produced a second EPIC-01 with the
    # goal and no stories, leaving the real one goal-less). Sections with the
    # same number are one epic; their stories and goal merge.
    by_number: dict[str, Epic] = {}
    for i, em in enumerate(epic_marks):
        epic_n = int(em.group(1))
        end = epic_marks[i + 1].start() if i + 1 < len(epic_marks) else len(text)
        section = text[em.end():end]
        epic = by_number.get(epic_id(epic_n))
        if epic is None:
            epic = Epic(id=epic_id(epic_n), title=em.group(2).strip())
            by_number[epic.id] = epic
            plan.epics.append(epic)

        story_marks = list(_STORY_HEADING.finditer(section))
        goal = " ".join(
            section[: story_marks[0].start() if story_marks else len(section)].split()
        )[:600]
        if len(goal) > len(epic.goal):
            epic.goal = goal

        for j, sm in enumerate(story_marks):
            s_end = story_marks[j + 1].start() if j + 1 < len(story_marks) else len(section)
            body = section[sm.end():s_end]
            story = Story(
                id=story_id(epic_n, sm.group(2)),
                epic_id=epic.id,
                title=sm.group(3).strip(),
                body=body.strip(),
            )

            role = _ROLE_LINE.search(body)
            if role:
                story.as_a, story.i_want, story.so_that = _role_parts(role)

            ac = _AC_BLOCK.search(body)
            if ac:
                story.acceptance_criteria = _split_ac(ac.group(1))

            meta = _parse_story_meta(body, epic_n)
            story.covers = meta.get("covers", [])
            story.write_scope = with_lockfiles(meta.get("write_scope", []))
            story.depends_on = [d for d in meta.get("depends_on", []) if d != story.id]
            story.screens = meta.get("screens", [])
            story.verification_contract = meta.get("verification_contract", [])

            epic.stories.append(story)

    # Coverage map is the fallback source: if a story doesn't declare `covers`
    # it comes from here, because missing FR mappings make the machine gate
    # block the entire story set.
    for fr, sids in plan.coverage_map.items():
        for sid in sids:
            st = plan.by_id(sid)
            if st and fr not in st.covers:
                st.covers.append(fr)

    return plan


def parse_epics_file(path: Path | str) -> EpicPlan:
    return parse_epics(Path(path).read_text(encoding="utf-8", errors="replace"))


# ---------------------------------------------------------- architecture.md

#: `### AR-1 — Single write path`
_AR_HEADING = re.compile(r"^#{2,4}\s+((?:AR|AD)-\d+)\s*[—–:-]\s*(.+?)\s*$", re.MULTILINE | re.IGNORECASE)
_AR_FIELD = re.compile(r"^[-*]\s*\*\*(Binds|Prevents|Rule)\s*[:：]?\*\*\s*(.+)$", re.MULTILINE)


@dataclass
class Decision:
    """An architectural decision that stories must comply with."""

    id: str
    title: str
    #: Requirement codes this decision binds — this is how to select the right
    #: decisions for a story without guessing.
    binds: list[str] = field(default_factory=list)
    #: Decision applies to **all** stories (`Binds: all`, or no bindings
    #: declared). This is a baseline rule, not a requirement-specific one.
    universal: bool = False
    prevents: str = ""
    rule: str = ""
    text: str = ""

    def as_prompt(self) -> str:
        parts = [f"**{self.id} — {self.title}**"]
        if self.rule:
            parts.append(f"Rule: {self.rule}")
        if self.prevents:
            parts.append(f"Prevents: {self.prevents}")
        return "\n".join(parts)


def _chi_phi_chuc_nang(binds: list[str]) -> bool:
    """Whether a decision binds **only** non-functional requirements.

    Stories declare the functional requirements they cover, so a decision
    bound to `NFR-1, NFR-3` joins with nothing and reaches no session — which
    is how a real run sent every implementing agent to build a localStorage
    app without the decision naming the storage key (bug 93). Non-functional
    requirements are cross-cutting by construction, so decisions bound only to
    them bind the whole build.
    """
    return bool(binds) and all(b.upper().startswith("NFR-") for b in binds)


@dataclass
class Architecture:
    decisions: list[Decision] = field(default_factory=list)

    def by_id(self, ar_id: str) -> Decision | None:
        return next((d for d in self.decisions if d.id == ar_id), None)

    def for_requirements(self, fr_ids: list[str]) -> list[Decision]:
        """Decisions binding any requirement in the list.

        Thanks to the ``**Binds:**`` field, selecting context for a story is
        a **lookup**, not a judgment call: loading the entire 26KB architecture
        document into every session is both expensive and diluting, and
        letting the agent self-select means every session selects differently.
        """
        want = set(fr_ids)
        return [
            d for d in self.decisions
            if d.universal or (want & set(d.binds)) or _chi_phi_chuc_nang(d.binds)
        ]


#: How much of a multi-line `**Rule:**` block travels into the prompt. The
#: rule is quoted verbatim in every session the decision binds, so it is
#: bounded — but generously: the table under AD-3 in a real run *was* the rule.
MAX_RULE_CHARS = 1500


def parse_architecture(text: str) -> Architecture:
    arch = Architecture()
    marks = list(_AR_HEADING.finditer(text))
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        # The last decision is not the last section of the document: bound it
        # at the next heading of the same level or shallower (bug 93 — AD-5's
        # body ran on through Stack, Structural Seed and Deferred).
        muc = len(m.group(0)) - len(m.group(0).lstrip("#"))
        ke = re.compile(r"^#{1,%d}\s" % muc, re.MULTILINE).search(text, m.end(), end)
        if ke:
            end = ke.start()
        body = text[m.end():end]
        d = Decision(id=m.group(1), title=m.group(2).strip(), text=body.strip())
        seen_binds = False
        fields = list(_AR_FIELD.finditer(body))
        for j, f in enumerate(fields):
            seen_binds = seen_binds or f.group(1).lower() == "binds"
            key, value = f.group(1).lower(), " ".join(f.group(2).split())
            if key == "binds":
                d.binds = _expand_fr_refs(value) + re.findall(r"\b(?:AR|AD)-\d+\b", value)
                d.universal = bool(re.search(r"\b(all|mọi story|toàn bộ)\b", value, re.I))
            elif key == "prevents":
                d.prevents = value
            else:
                # A rule can continue past its own line — a table of fields, a
                # list, a code block (bug 94: `Rule: Every note is an object
                # with exactly three fields:` reached the agent with the three
                # fields cut off).
                tail = body[f.end():fields[j + 1].start() if j + 1 < len(fields) else None]
                d.rule = (value + "\n" + tail.strip()).strip()[:MAX_RULE_CHARS]
        # No bindings declared = baseline rule, applies to all stories. Treating
        # it as "applies to no story" would drop exactly the most important rules
        # — and the same hole opens when bindings *are* declared but none of them
        # parse (bug 93: `Binds: NFR-1, NFR-3` read as an empty list, so two
        # decisions bound nothing and reached no session).
        d.universal = d.universal or not seen_binds or not d.binds
        arch.decisions.append(d)
    return arch


def parse_architecture_file(path: Path | str) -> Architecture:
    return parse_architecture(Path(path).read_text(encoding="utf-8", errors="replace"))
