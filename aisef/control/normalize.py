"""Convert BMAD documents to structured data.

This is the **boundary that keeps BMAD as a dependency, not a foundation**
(decision D4). The framework owns its own data model; BMAD produces
markdown, this module translates it into that model. Switching from BMAD to
another tool only requires a new translator; orchestration and gates are
untouched.

Document shape observed from real PRDs generated by BMAD (spike S6, fixture
`tests/fixtures/bmad/prd.md`), not guessed:

* functional requirements: ``#### FR-1: Title`` then description, then a
  ``**Consequences (testable):**`` section — which are the acceptance
  criteria, already in verifiable form;
* non-functional requirements: ``- **NFR-1 — Title.** description``;
* assumptions: marked ``[ASSUMPTION: ...]`` inline where they arise;
* open questions: ``OQ-n``, with affected scope when present.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from .experience import slugify

#: `#### FR-1: Create note`
_FR_HEADING = re.compile(
    r"^#{2,5}\s+(FR-\d+)\s*[:：—–-]\s*(.+?)\s*$", re.MULTILINE | re.IGNORECASE
)

#: `- **NFR-1 — App launch time.** From the moment...` — and the shape where
#: the bold span holds the ID alone, with no title: `- **NFR-1:** The app
#: starts in under 2s.` (bug 88, 2026-09-13: real planner output; the whole
#: NFR section was dropped and the gate warned "no non-functional
#: requirements" about a document that had four).
_NFR_ITEM = re.compile(
    r"^(?:[-*]\s+\*\*(NFR-\d+)\s*[:：—–-]\s*(.+?)\.?\*\*\s*(.*)"
    r"|#{2,5}\s+\*{0,2}(NFR-\d+)\s*[:：—–-]\s*(.+?)\s*\*{0,2}"
    r"|[-*]\s+\*\*(NFR-\d+)\s*[:：—–-]?\s*\*\*\s*[:：—–-]?\s*(.+?))\s*$",
    re.MULTILINE | re.IGNORECASE,
)
#: Section heading for NFR block — Vietnamese or English.
#: Used as fallback: auto-number unlabelled bullets when the heading is present
#: but the agent omitted NFR-N IDs.
_NFR_SECTION = re.compile(
    r"^#{2,5}\s+.*(?:Yêu cầu phi chức năng|Non-?functional\s+Requirements?)"
    r"\s*$",
    re.MULTILINE | re.IGNORECASE,
)
_PLAIN_BULLET = re.compile(r"^(?:[-*]|\d+[.):])\s+(.+?)\s*$", re.MULTILINE)

#: Criteria block heading — agent writes in English or Vietnamese depending on
#: the run (bug 19, 2026-09-05: second `plan` run wrote Vietnamese heading and
#: PRD gate dropped all 14 FRs because parser only knew "Consequences (testable)").
_CONSEQUENCES_HEAD = (
    r"(?:Consequences\s*\(testable\)"
    r"|(?:Testable|Verifiable|Acceptance|Verification|Test)\s+(?:criteria|consequences|conditions)"
    r"|Criteria"
    r"|Hệ quả(?:\s+kiểm chứng(?:\s+được)?|\s*\([^)]*\))?"
    r"|Tiêu chí(?:\s+(?:kiểm chứng(?:\s+được)?|chấp nhận|xác nhận|nghiệm thu|kiểm tra))?"
    r")"
)
_CONSEQUENCES = re.compile(
    r"(?:\*\*" + _CONSEQUENCES_HEAD + r"\s*[:：]?\*\*"
    r"|#{2,5}\s+" + _CONSEQUENCES_HEAD + r")"
    r"\s*[:：]?\s*\n(.*?)(?=\n#{2,5}\s|\n\*\*|\Z)",
    re.IGNORECASE | re.DOTALL,
)
_BULLET = re.compile(r"^(?:[-*]|\d+[.):])\s+(.+?)\s*$", re.MULTILINE)

_ASSUMPTION = re.compile(r"\[ASSUMPTION:\s*(.+?)\]", re.DOTALL | re.IGNORECASE)
_OQ_MENTION = re.compile(r"\b(OQ-\d+)\b")
#: `**OQ-1 (blocks FR-13..FR-15)** — ...` or `- **OQ-1:** ...`
_OQ_DEFINITION = re.compile(
    r"(?:\*\*(OQ-\d+)\s*(?:\(([^)]*)\))?\s*[:：]?\s*\*\*\s*[—–:：-]?\s*(.+?)"
    r"|#{2,5}\s+(OQ-\d+)\s*(?:\(([^)]*)\))?\s*[:：—–-]\s*(.+?))"
    r"(?=\n[-*]\s+\*\*OQ-|\n\d+\.\s+\*\*OQ-|\n#{2,5}\s+OQ-|\n\d+\.\s|\n\n|\Z)",
    re.DOTALL | re.IGNORECASE,
)
#: Section heading for assumptions — used as fallback when inline
#: `[ASSUMPTION: ...]` markers are absent.
_ASSUMPTION_SECTION = re.compile(
    r"^#{2,5}\s+.*(?:Assumptions|Giả định)\s*$",
    re.MULTILINE | re.IGNORECASE,
)
_SECTION_ASSUMPTION_ITEM = re.compile(
    r"^[-*]\s+(?:\*\*[^*]+\*\*\s*[:：]?\s*)?(.+?)\s*$",
    re.MULTILINE,
)
_FR_RANGE = re.compile(r"\b(N?FR)-(\d+)\s*\.\.\s*(?:N?FR-)?(\d+)", re.IGNORECASE)
_FR_SINGLE = re.compile(r"\b(N?FR)-(\d+)\b", re.IGNORECASE)


@dataclass
class Requirement:
    id: str
    kind: str  # "functional" | "non_functional"
    title: str
    description: str = ""
    #: Testable consequences — used directly as story acceptance criteria.
    acceptance_criteria: list[str] = field(default_factory=list)
    open_questions: list[str] = field(default_factory=list)

    @property
    def is_testable(self) -> bool:
        """A requirement without testable criteria cannot be accepted."""
        return bool(self.acceptance_criteria)


@dataclass
class OpenQuestion:
    id: str
    text: str
    #: Requirements blocked until this question is answered.
    blocks: list[str] = field(default_factory=list)


#: Lockfiles follow their manifest. Package managers write lockfiles as a
#: **consequence** of any dependency change — declaring the manifest without
#: the lockfile is declaring half of an indivisible pair.
#:
#: Measured on e9: AC 1 of STORY-01-01 required "lockfile is committed", but
#: `write_scope` only had `package.json`. Guard blocked lockfile write, agent
#: followed instructions — reverted it and reported missing scope — reviewer
#: blocked correctly because AC 1 failed, and the retry loop ran 4 identical
#: times, $9.85 for a deadlock with no way out.
#: Dependency manifest files. Any story may need to add a package — blocking
#: it creates a deadlock that burns the entire retry budget before surfacing.
MANIFESTS = (
    "package.json", "pyproject.toml", "requirements.txt", "requirements.in",
    "Cargo.toml", "go.mod", "Gemfile", "composer.json",
)

LOCKFILES: dict[str, tuple[str, ...]] = {
    "package.json": ("package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb"),
    "pyproject.toml": ("poetry.lock", "uv.lock", "pdm.lock"),
    "requirements.in": ("requirements.txt",),
    "Cargo.toml": ("Cargo.lock",),
    "go.mod": ("go.sum",),
    "Gemfile": ("Gemfile.lock",),
    "composer.json": ("composer.lock",),
}


def effective_write_scope(story: Story, project: Path) -> list[str]:
    """Effective write scope: story-declared scope plus dependency manifests.

    BMAD lists source files in ``write_scope``; it does not anticipate that
    the story will need to declare a package. But acceptance criteria do —
    "test on ``fake-indexeddb``", "lockfile is committed" — and then the
    story cannot satisfy its own criteria. Measured on e9: two consecutive
    stories deadlocked for this reason, $20 for eight attempts with none
    passing.

    Only add files that **actually exist** in the project: adding blindly
    widens scope without changing anything, and the scope list printed for
    the agent gains meaningless lines.

    Deliberately does **not** touch the scope the scheduler uses for wave
    splitting: the question there is different — whether two stories
    overlap — and including manifests would make every story overlap,
    killing parallel execution.
    """
    scope = list(story.write_scope)
    for name in MANIFESTS:
        if name not in scope and (project / name).is_file():
            scope.append(name)
    for path in verification_paths(story, project):
        if path not in scope:
            scope.append(path)
    return with_lockfiles(scope)


#: Verification kind -> config key holding the command to run it.
_VERIFY_COMMAND_KEY = {"unit": "tools.test"}


_JS_CONFIGS = {
    # Node's built-in runner has no config file. Naming it here keeps a project
    # that runs `node --test` from being granted write scope over jest,
    # vitest, cypress and mocha config files it has never had (bug 108): a
    # write scope is a permission, and permission to touch a file the project
    # does not use is not free.
    "node --test": (),
    "playwright": ("playwright.config.js", "playwright.config.ts"),
    "jest": ("jest.config.js", "jest.config.ts", "jest.config.mjs"),
    "vitest": ("vitest.config.js", "vitest.config.ts", "vitest.config.mts"),
    "cypress": ("cypress.config.js", "cypress.config.ts"),
    "mocha": (".mocharc.yml", ".mocharc.json"),
}
_PY_CONFIGS = ("pytest.ini", "conftest.py")
_JS_DIRS = ("tests", "test", "__tests__", "spec", "e2e")
_PY_DIRS = ("tests", "test")


def _stack_test_paths(project: Path, commands: list[str]) -> tuple[list[str], list[str]]:
    """Return (dirs, configs) narrowed to the project's actual stack."""
    # resolve `npm test` / `npm run X` through package.json
    resolved = list(commands)
    pkg_path = project / "package.json"
    if pkg_path.is_file():
        try:
            import json
            scripts = json.loads(pkg_path.read_text(encoding="utf-8")).get("scripts", {})
            for cmd in commands:
                parts = cmd.strip().split()
                if len(parts) >= 2 and parts[0] == "npm":
                    key = parts[1] if parts[1] != "run" else (parts[2] if len(parts) > 2 else "")
                    if key in scripts:
                        resolved.append(scripts[key])
        except Exception:  # noqa: BLE001
            pass
    joined = " ".join(resolved).lower()
    has_js = pkg_path.is_file()
    has_py = any((project / m).is_file() for m in ("pyproject.toml", "setup.py", "setup.cfg"))
    # detect framework from commands
    frameworks = [fw for fw in _JS_CONFIGS if fw in joined]
    if frameworks:
        dirs = list(dict.fromkeys(d for d in _JS_DIRS))
        cfgs = [c for fw in frameworks for c in _JS_CONFIGS[fw]]
        return dirs, cfgs
    if "pytest" in joined or "python" in joined:
        return list(_PY_DIRS), list(_PY_CONFIGS)
    # fallback to project markers
    if has_js and not has_py:
        dirs = list(_JS_DIRS)
        cfgs = [c for fw_cfgs in _JS_CONFIGS.values() for c in fw_cfgs]
        return dirs, cfgs
    if has_py and not has_js:
        return list(_PY_DIRS), list(_PY_CONFIGS)
    # both or neither: add everything
    dirs = list(dict.fromkeys(list(_JS_DIRS) + list(_PY_DIRS)))
    cfgs = [c for fw_cfgs in _JS_CONFIGS.values() for c in fw_cfgs] + list(_PY_CONFIGS)
    return dirs, cfgs


def verification_paths(story: Story, project: Path, config=None) -> list[str]:
    """Test directories/files the **story's verification contract** requires.

    Bug 21 (e9 2026-09-05): story declared `e2e` and `accessibility` but
    write_scope only had `src/**`; guard blocked writing `tests/`, $30 wasted.
    If the harness requires tests, it must grant scope to write them.

    Bug 22 (e9 2026-09-08, greenfield): verification_paths only added paths
    that **exist**, but in a greenfield project the test directory doesn't
    exist yet — the story must CREATE it. Now also adds conventional test
    dirs and config files when the verification contract requires test kinds.
    """
    kinds = [k.strip().lower() for k in (story.verification_contract or []) if k.strip()]
    if not kinds:
        return []
    if config is None:
        from ..config import Config

        try:
            config = Config.load(project)
        except Exception:  # noqa: BLE001 — no config means nothing to infer
            return []
    out: list[str] = []
    needs_tests = any(k in kinds for k in ("unit", "e2e", "accessibility", "integration"))

    for kind in kinds:
        key = _VERIFY_COMMAND_KEY.get(kind, f"verify.{kind}")
        try:
            cmd = str(config[key] or "")
        except KeyError:
            continue
        for tok in cmd.replace("'", " ").replace('"', " ").split():
            if tok.startswith("-") or "/" not in tok:
                continue
            rel = tok.strip("./").rstrip("/")
            if not rel or rel.startswith("..") or rel.startswith("node_modules"):
                continue
            if rel not in out:
                out.append(rel)

    if needs_tests and not out:
        commands = []
        for kind in kinds:
            key = _VERIFY_COMMAND_KEY.get(kind, f"verify.{kind}")
            try:
                cmd = str(config[key] or "")
            except KeyError:
                continue
            if cmd:
                commands.append(cmd)
        dirs, cfgs = _stack_test_paths(project, commands)
        for d in dirs:
            if d not in out:
                out.append(d)
        for cfg in cfgs:
            if cfg not in out:
                out.append(cfg)

    return out


def is_lockfile(path: str) -> bool:
    """Is this path a lockfile added by `with_lockfiles`?

    The "story touches too many places" threshold measures **how large the
    story declares itself**. Lockfiles are an automatic consequence of the
    manifest, so counting them toward the threshold would turn a correct
    patch into a gate failure.
    """
    name = path.rstrip("/").rsplit("/", 1)[-1]
    return any(name in locks for locks in LOCKFILES.values())


def with_lockfiles(scope: list[str]) -> list[str]:
    """Add lockfiles of every manifest in scope.

    Adds the **entire family** of lockfiles for each manifest rather than
    guessing the package manager in use: an extra path in scope does not
    meaningfully loosen it — a non-existent file cannot be written — but
    guessing wrong puts the story right back into the same deadlock.
    """
    have = set(scope)
    out = list(scope)
    for path in scope:
        name = path.rstrip("/").rsplit("/", 1)[-1]
        prefix = path[: len(path) - len(name)]
        for lock in LOCKFILES.get(name, ()):
            if prefix + lock not in have:
                have.add(prefix + lock)
                out.append(prefix + lock)
    return out


@dataclass
class PRD:
    requirements: list[Requirement] = field(default_factory=list)
    assumptions: list[str] = field(default_factory=list)
    open_questions: list[OpenQuestion] = field(default_factory=list)

    def functional(self) -> list[Requirement]:
        return [r for r in self.requirements if r.kind == "functional"]

    def non_functional(self) -> list[Requirement]:
        return [r for r in self.requirements if r.kind == "non_functional"]

    def by_id(self, req_id: str) -> Requirement | None:
        return next((r for r in self.requirements if r.id == req_id), None)

    def blocked_ids(self) -> set[str]:
        """Requirements blocked by open questions — must not be included in stories."""
        blocked: set[str] = set()
        for oq in self.open_questions:
            blocked |= set(oq.blocks)
        return blocked

    def untestable(self) -> list[Requirement]:
        return [r for r in self.functional() if not r.is_testable]

    def as_dict(self) -> dict:
        return {
            "requirements": [
                {
                    "id": r.id,
                    "kind": r.kind,
                    "title": r.title,
                    "description": r.description,
                    "acceptance_criteria": r.acceptance_criteria,
                    "open_questions": r.open_questions,
                }
                for r in self.requirements
            ],
            "assumptions": self.assumptions,
            "open_questions": [
                {"id": q.id, "text": q.text, "blocks": q.blocks}
                for q in self.open_questions
            ],
        }


def _expand_fr_refs(text: str) -> list[str]:
    """`FR-13..FR-15` -> [FR-13, FR-14, FR-15]; includes single references too.

    Non-functional codes count as references (bug 93): a decision that binds
    `NFR-1, NFR-3` used to parse to an empty list, which made it bind nothing.
    """
    ids: list[str] = []
    consumed = text
    for m in _FR_RANGE.finditer(text):
        kind = m.group(1).upper()
        start, end = int(m.group(2)), int(m.group(3))
        if start <= end and end - start < 100:
            ids.extend(f"{kind}-{n}" for n in range(start, end + 1))
            consumed = consumed.replace(m.group(0), " ")
        # Reversed or overly wide range is a writing error. Not expanded, but
        # also not removed from text — the two codes at each end are still
        # picked up as single references. Blocking one extra is safer than
        # missing both.
    ids.extend(f"{m.group(1).upper()}-{m.group(2)}" for m in _FR_SINGLE.finditer(consumed))
    return sorted(set(ids), key=lambda s: (s.split("-")[0], int(s.split("-")[1])))


def _section_for(text: str, start: int, next_start: int | None) -> str:
    return text[start : next_start if next_start is not None else len(text)]


def parse_prd(text: str) -> PRD:
    """Parse a BMAD PRD into the framework's data model."""
    prd = PRD()

    fr_matches = list(_FR_HEADING.finditer(text))
    for i, m in enumerate(fr_matches):
        body = _section_for(
            text, m.end(), fr_matches[i + 1].start() if i + 1 < len(fr_matches) else None
        )

        criteria: list[str] = []
        cons = _CONSEQUENCES.search(body)
        if cons:
            criteria = [b.group(1).strip() for b in _BULLET.finditer(cons.group(1))]

        # Fallback: last bold-text heading or markdown heading followed by a
        # bullet/numbered list in the FR body.
        if not criteria:
            _last_block = None
            for _fb in re.finditer(
                r"(?:^\*\*[^*\n]+\*\*|^#{3,5}\s+\S[^\n]*)[:：]?\s*$\s*\n",
                body, re.MULTILINE,
            ):
                _rest = body[_fb.end():]
                _end = re.search(r"\n#{2,5}\s|\n\*\*|\Z", _rest, re.MULTILINE)
                _blk = _rest[: _end.start()] if _end else _rest
                _items = [b.group(1).strip() for b in _BULLET.finditer(_blk)]
                if _items:
                    _last_block = (_fb, _items)
            if _last_block:
                cons, criteria = _last_block[0], _last_block[1]

        description = body[: cons.start()] if cons else body
        description = _ASSUMPTION.sub("", description)

        prd.requirements.append(
            Requirement(
                id=m.group(1),
                kind="functional",
                title=m.group(2).strip(),
                description=" ".join(description.split())[:600],
                acceptance_criteria=criteria,
                open_questions=sorted(set(_OQ_MENTION.findall(body))),
            )
        )

    nfr_matches = list(_NFR_ITEM.finditer(text))
    for i, m in enumerate(nfr_matches):
        nfr_id = m.group(1) or m.group(4) or m.group(6)
        nfr_title = m.group(2) or m.group(5) or ""
        nfr_desc = m.group(3) or m.group(7) or ""
        if not nfr_title.strip():
            # `- **NFR-1:** text` carries no title of its own. An empty title
            # is a blocking gate error, so the first sentence becomes one.
            nfr_title = re.split(r"(?<=[.!?])\s", nfr_desc.strip(), maxsplit=1)[0]
            nfr_title = " ".join(nfr_title.split()).rstrip(".")[:120]
        if m.group(4) and not nfr_desc:
            body_start = m.end()
            body_end = nfr_matches[i + 1].start() if i + 1 < len(nfr_matches) else None
            nfr_desc = _section_for(text, body_start, body_end)
        prd.requirements.append(
            Requirement(
                id=nfr_id,
                kind="non_functional",
                title=nfr_title.strip(),
                description=" ".join(_ASSUMPTION.sub("", nfr_desc).split())[:600],
                open_questions=sorted(set(_OQ_MENTION.findall(
                    text[m.start():nfr_matches[i + 1].start()] if i + 1 < len(nfr_matches)
                    else text[m.start():]
                ))),
            )
        )

    # Fallback: agent wrote NFR section but omitted NFR-N IDs — auto-number.
    if not prd.non_functional():
        sec = _NFR_SECTION.search(text)
        if sec:
            after = text[sec.end():]
            end = re.search(r"\n#{2,5}\s", after)
            block = after[: end.start()] if end else after
            for i, bm in enumerate(_PLAIN_BULLET.finditer(block), start=1):
                line = bm.group(1).strip()
                if not line or line.startswith("#"):
                    break
                parts = re.split(r"[—–-]\s+", line, maxsplit=1)
                title = parts[0].strip().strip("*").strip()
                desc = parts[1].strip() if len(parts) > 1 else ""
                prd.requirements.append(
                    Requirement(
                        id=f"NFR-{i}",
                        kind="non_functional",
                        title=title,
                        description=desc[:600],
                    )
                )

    seen_assumptions: set[str] = set()
    for m in _ASSUMPTION.finditer(text):
        a = " ".join(m.group(1).split())
        if a not in seen_assumptions:
            seen_assumptions.add(a)
            prd.assumptions.append(a)

    # Fallback: assumptions in a dedicated section (no inline markers).
    if not prd.assumptions:
        asec = _ASSUMPTION_SECTION.search(text)
        if asec:
            after = text[asec.end():]
            end = re.search(r"\n#{2,5}\s", after)
            block = after[: end.start()] if end else after
            for bm in _SECTION_ASSUMPTION_ITEM.finditer(block):
                a = " ".join(bm.group(1).split())
                if a and a not in seen_assumptions:
                    seen_assumptions.add(a)
                    prd.assumptions.append(a)

    seen_oq: set[str] = set()
    for m in _OQ_DEFINITION.finditer(text):
        oq_id = m.group(1) or m.group(4)
        if oq_id in seen_oq:
            continue
        seen_oq.add(oq_id)
        prd.open_questions.append(
            OpenQuestion(
                id=oq_id,
                text=" ".join((m.group(3) or m.group(6)).split())[:400],
                blocks=_expand_fr_refs(m.group(2) or m.group(5) or ""),
            )
        )

    return prd


def parse_prd_file(path: Path | str) -> PRD:
    return parse_prd(Path(path).read_text(encoding="utf-8", errors="replace"))


