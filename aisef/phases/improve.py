def epic_counts(led: Ledger, epic_id: str) -> dict:
    """VERIFIED/GAP/REOPENED of **behaviors belonging to the epic** -- what the loop targets.

    Global delta (R7) is not used as a stopping condition: the repair story
    itself spawns additional behaviors (`AC-STORY-RP-nn-1`, `qa:fake-tests`)
    and makes delta positive even without closing any gap -- measured on a fake
    client: a round that fixes nothing still gets V+1.
    """
    out = {"epic_verified": 0, "epic_gap": 0, "epic_reopened": 0}
    for b in led.behaviors.values():
        if led.epic_of(b.story) == epic_id:
            out[f"epic_{b.status}"] = out.get(f"epic_{b.status}", 0) + 1
    return out


def epic_gaps(led: Ledger, epic_id: str) -> list[Behavior]:
    """GAP/REOPENED whose owning story belongs to the epic -- REOPENED first, then by id.

    The owning story is the story in the index, not the repair story: behaviors
    of `EPIC-RP-*` (the repair story's own criteria) do not cycle back as new gaps.
    """
    out = [
        b for b in led.behaviors.values()
        if b.status in (GAP, REOPENED) and led.epic_of(b.story) == epic_id
    ]
    return sorted(out, key=lambda b: (b.status != REOPENED, b.id))


#: Behavior kinds entering the auto-repair **queue**, by priority order (decision B6
#: 2026-09-06): criteria with a test id are the most specific verifier; requirements
#: (fr/nfr) proven via the covering story's criteria; screens via visual contract.
#: `qa:*` is **project-level** aggregation (one `aisef qa` run), with no per-story
#: verifier -- outside the queue, handled by `aisef qa --only <kind>`.  Measured B1
#: on e9: rounds 4-5 received `qa:*`, delta -1/-2.
QUEUE_RANK = {"ac": 0, "fr": 1, "nfr": 1, "mockup": 2}

#: What closes each kind of absence (ADR-009 O2).  Three absences were recorded as
#: one GAP and all three got the same paid repair story; only `UNBUILT` is worth
#: one.  `UNTRACED` never enters the queue: the owner decision of 2026-09-06 §4
#: ("a gap that is only missing traceability is fixed by the harness, not by a
#: story") is this dict plus the filter in `repair_queue`.
REPAIR_ACTION = {UNBUILT: "story", UNTESTED: "test-only story", UNTRACED: "harness metadata fix"}


def repair_queue(gaps: list[Behavior]) -> list[Behavior]:
    """Gaps eligible for auto-repair, REOPENED first, then by `QUEUE_RANK`, then id.

    `UNTRACED` is filtered out: the harness has no test name to attach to the
    behaviour, and no amount of agent time buys one — `aisef evidence <id> --link`
    (or a reporter that prints test names) does.  Spending a repair story there
    pays for a metadata edit at story prices.
    """
    return sorted((b for b in gaps if b.kind in QUEUE_RANK and b.gap_kind != UNTRACED),
                  key=lambda b: (b.status != REOPENED, QUEUE_RANK[b.kind], b.id))


