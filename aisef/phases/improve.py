#: Baseline before the first round of a call.  Recorded when the ledger has
#: changed since the last baseline (stories usually run between two `improve`
#: calls) or the last baseline belongs to another epic, so the next round's
#: delta correctly measures what that round produced for that epic.
BASELINE = "loop-0"
LOOP_REPORT = "LOOP-REPORT-{n}.md"
STORY_PREFIX = "STORY-RP-"


def repair_epic(epic_id: str) -> str:
    """`EPIC-01` -> `EPIC-RP-01`."""
    return "EPIC-RP-" + epic_id.removeprefix("EPIC-")


@dataclass
class Loop:
    """One round: enough to write the report and for the human to decide continue or stop."""

    n: int                      # label `loop-<n>` in ledger -- global, unique
    epic_loop: int              # which round of this epic
    story_id: str
    behavior: str
    before: dict                # summary + list of epic gaps, before the round
    after: dict = field(default_factory=dict)
    cost_usd: float = 0.0
    done: bool = False
    outcome_text: str = ""
    stuck: str = ""             # reviewer's note when the plan is stuck
    d_verified: int = 0
    d_reopened: int = 0
    report_path: Path | None = None

    @property
    def improvement(self) -> int:
        return self.d_verified - self.d_reopened

    def line(self) -> str:
        return (
            f"loop-{self.n} · {self.story_id} fixes {self.behavior} · "
            f"{'DONE' if self.done else 'NOT DONE'} · ${self.cost_usd:.2f} · "
            f"V{self.d_verified:+d} R{self.d_reopened:+d} · epic gaps "
            f"{len(self.before['gaps'])}→{len(self.after.get('gaps', []))}"
        )


@dataclass
class ImproveReport:
    epic: str
    loops: list[Loop] = field(default_factory=list)
    stopped: str = ""
    gaps_left: list[str] = field(default_factory=list)
    error: str = ""
    reconciled: list = field(default_factory=list)
    qualification: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.error and not self.gaps_left and not self.qualification

    @property
    def cost_usd(self) -> float:
        return sum(lo.cost_usd for lo in self.loops)

    def summary(self) -> str:
        if self.error:
            return f"improve {self.epic}: ✗ {self.error}"
        lines = [f"improve {self.epic}: {len(self.loops)} round(s) this run, ${self.cost_usd:.2f}"]
        lines += [f"↺ {r.line()}" for r in self.reconciled]
        lines += [f"  {lo.line()}" for lo in self.loops]
        for lo in self.loops:
            if lo.report_path:
                lines.append(f"  report: {lo.report_path}")
        lines.append(f"⏸ stop: {self.stopped}")
        if self.gaps_left:
            lines.append(f"  {len(self.gaps_left)} epic gap(s) remaining: "
                         + ", ".join(self.gaps_left[:5]))
        return "\n".join(lines)


