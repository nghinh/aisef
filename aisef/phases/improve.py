"""Evidence-based epic improvement loop (ADR-004 R3): `aisef improve --epic E`.

HoH proved the "measure gap -> fix -> re-measure" loop creates gain, but running
T = 70 rounds with no stopping condition doesn't work.  Here the loop is
**composed** from existing pieces -- no new phase, no changes to `run`/`implement`
-- and stops by code:

    qa.run_suite (project-level evidence at HEAD) -> ledger.build() -> GAP/REOPENED
    belonging to epic -> **one** repair story generated by code -> run.run_epic (new
    session, worktree, gate, reviewer != developer) -> QA again ->
    ledger.snapshot("loop-n") -> next round.

Five stopping conditions, all read from disk (ledger, evidence), not from process
memory -- so re-running resumes from the right place, no daemon needed:

1. no GAP/REOPENED remaining in epic;
2. reached `improve.max_loops` (counted per epic from `loops[]`);
3. marginal improvement delta(verified) - delta(reopened) <= 0 for
   `improve.flat_loops` consecutive rounds;
4. total cost of epic rounds exceeds `improve.cost_cap_usd`;
5. repair story plan stuck (`[stuck]`, reviewer verified) -> return to human.

Each round **one** repair story = **one** behavior: B1 requires cost <= 1 story per
round, and one behavior is the smallest unit the gate can score.  REOPENED goes
before GAP -- regression is what HoH measures.  Repair story is **deterministically**
generated from gap; agent enters at R10 after gain is measured.

Human gate `improve` before each round >= 2 (unless `--auto`): pipeline stops at
gate, human reads `LOOP-REPORT-<n>.md`, `aisef approve improve`, reruns -- same
mechanism as the other eight gates, approval binds to report hash.
"""

